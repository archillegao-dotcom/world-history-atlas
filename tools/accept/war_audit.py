    g = {}
    for r in res:
        g.setdefault(r["group"], [0, 0])[0 if r["ok"] else 1] += 1
    for k, (p, f) in g.items():
        print(f"{k}: {p}/{p + f}")
    tp = sum(r["ok"] for r in res)
    print(f"TOTAL {tp}/{len(res)} = {tp / len(res):.1%}")
