def run(flt=None):
    res = []
    for g, why, date, lat, lon, exp in C:
        if flt and flt not in g and flt not in why:
            continue
        t = time.time()
        r = {"group": g, "case": why, "date": date, "lat": lat, "lon": lon}
        try:
            loc = get("/api/locate", date=date, lat=lat, lon=lon)
            p = loc.get("polity")
            r["snap"] = loc.get("snapshot")
            if not p:
                r.update(ok=False, got="（没有多边形）")
            else:
                d = get("/api/modules/regime", date=date, snap=loc["snapshot"], fid=p["fid"])
                st = d.get("state") or {}
                nm = get(f"/api/snapshot_names/{loc['snapshot']}", date=date).get(str(p["fid"]), {})
                label = nm.get("zh") or st.get("name") or ""
                r.update(fid=p["fid"], poly=p.get("NAME"), qid=st.get("id"), name=st.get("name"), label=label,
                         flag=st.get("flag_file"), chain_now=(d.get("chain") or {}).get("now"))
                names = f"{label}|{st.get('name') or ''}"
                errs = []
                if exp.get("any_") and not (st.get("id") or label):
                    errs.append("面板无政权")
                if exp.get("qid") and st.get("id") not in exp["qid"]:
                    errs.append(f"QID {st.get('id')} 不在 {exp['qid']}")
                if exp.get("not_qid") and st.get("id") in exp["not_qid"]:
                    errs.append(f"不应为 {st.get('id')}")
                if exp.get("name") and not any(x in names for x in exp["name"]):
                    errs.append(f"名称「{names}」不含 {exp['name']}")
                if exp.get("not_name") and any(x in names for x in exp["not_name"]):
                    errs.append(f"名称「{names}」含禁止词 {exp['not_name']}")
                if exp.get("chain") and not any(x in "；".join(r["chain_now"] or []) for x in exp["chain"]):
                    errs.append(f"政权链当前 {r['chain_now']} 不含 {exp['chain']}")
                if exp.get("flag") and not any(x in urllib.parse.unquote(st.get("flag_file") or "") for x in exp["flag"]):
                    errs.append(f"国旗 {st.get('flag_file')} 不含 {exp['flag']}")
                if exp.get("leader") or exp.get("era"):
                    L = get("/api/modules/leaders", date=date, snap=loc["snapshot"], fid=p["fid"])
                    txt = json.dumps(L, ensure_ascii=False)
                    r["leaders"] = [h["person"].get("name") for h in L.get("heads", [])][:6]
                    for k in ("leader", "leader2", "era"):
                        if exp.get(k) and not any(x in txt for x in exp[k]):
                            errs.append(f"领导人/年号缺 {exp[k]}")
                r.update(ok=not errs, errors=errs)
        except Exception as e:
            r.update(ok=False, errors=[repr(e)[:200]])
        r["sec"] = round(time.time() - t, 1)
        res.append(r)
        print(("PASS " if r["ok"] else "FAIL ") + f"[{g}] {why} → {r.get('qid')} {r.get('label') or r.get('name')} {'' if r['ok'] else r.get('errors')} ({r['sec']}s)", flush=True)
    return res

if __name__ == "__main__":
    flt = sys.argv[1] if len(sys.argv) > 1 else None
    res = run(flt)
    out = "logs/accept_api.json" if not flt else f"logs/accept_api_{flt}.json"
    json.dump(res, open(out, "w"), ensure_ascii=False, indent=1)
    groups = {}
    for r in res:
        groups.setdefault(r["group"], [0, 0])[0 if r["ok"] else 1] += 1
    for g, (p, f) in groups.items():
        print(f"{g}: {p}/{p + f}")
    tp = sum(1 for r in res if r["ok"])
    print(f"TOTAL {tp}/{len(res)} = {tp / max(1, len(res)):.1%}")
