raw = lzma.decompress((ROOT / "data/control_zones.json.xz").read_bytes())
zones = []
for z in json.loads(raw)["zones"]:
    if z.get("kind") != "occupied" or not z.get("as_polity"):
        continue
    frm = z.get("from") or ""
    if frm < "1937-07-01" or frm >= "1946-01-01":
        continue
    zones.append((frm, z.get("until") or "", z["id"], shape(z["geom"])))

fails = []
for name, lon, lat, fall in CITIES:
    p = Point(lon, lat)
    hits = sorted(frm for frm, until, zid, g in zones if g.covers(p) or g.intersects(p))
    first = hits[0] if hits else None
    if first is None:
        print(f"FAIL {name} 没有占领层")
        fails.append(name)
        continue
    if first < fall:
        print(f"FAIL {name} 占领层 {first} 早于沦陷日 {fall}")
        fails.append(name)
    elif first > fall:
        print(f"NOTE {name} 占领层 {first} 晚于沦陷日 {fall}")
    else:
        print(f"PASS {name} 占领层 {first}")

for name, lon, lat, fall, end in ENDED:
    p = Point(lon, lat)
    on_fall = []
    on_end = []
    for frm, until, zid, g in zones:
        if not (g.covers(p) or g.intersects(p)):
            continue
        # until 不含当天。撤回日当天不得再被盖住。
        if frm <= fall < (until or "9999"):
            on_fall.append(frm)
        if frm <= end < (until or "9999"):
            on_end.append(f"{frm}→{until} {zid}")
    if not on_fall:
        print(f"FAIL {name} {fall} 没有占领层")
        fails.append(name)
    elif on_end:
        print(f"FAIL {name} {end} 仍在占领层 {on_end[0]}")
        fails.append(name + "-end")
    else:
        print(f"PASS {name} {on_fall[0]} 收到 {end}")

