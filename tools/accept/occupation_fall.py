def locate(date, lat, lon):
    q = urllib.parse.urlencode({"date": date, "lat": lat, "lon": lon})
    url = f"http://127.0.0.1:{os.environ.get('WHA_PORT', '8792')}/api/locate?{q}"
    return json.load(urllib.request.urlopen(url, timeout=180))["polity"]


